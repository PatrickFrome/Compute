export function subjectForFolder(folderId,folders){
  const visited=new Set();let f=folders.find(x=>x.id===folderId);
  while(f&&f.parent_id){
    if(visited.has(f.id))return null;
    visited.add(f.id);f=folders.find(x=>x.id===f.parent_id);
  }
  const match=/^subject-(\d+)$/.exec(f?.id||'');
  return match?Number(match[1]):null;
}
