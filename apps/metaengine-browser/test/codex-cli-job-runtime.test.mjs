import {CODEX_CLI_JOB_PROTOCOL} from '../src/codex-cli-physical-settlement.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import childProcess from 'node:child_process';
import { syncBuiltinESMExports } from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createCodexCliWindowsProcessController, resolveCodexCliJobHelper,
  resolveCodexCliJobHelperSource, resolveCodexCliJobRuntime, verifyCodexCliJobHelper } from '../src/codex-cli-windows-process-controller.mjs';

const sha = bytes => createHash('sha256').update(bytes).digest('hex');

// These generated byte bindings test the launch gate only. They contain no
// compiled assembly and do not qualify Windows, a compiler or a Job Object.
function fixture(t, packaged = false) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'metaengine-codex-runtime-pin-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const resourcesPath = path.join(root, 'resources'), appRoot = packaged ? path.join(resourcesPath, 'app.asar') : path.join(root, 'app');
  const moduleUrl = pathToFileURL(path.join(appRoot, 'src', 'codex-cli-windows-process-controller.mjs')).href;
  const options = { moduleUrl, resourcesPath }, runtime = resolveCodexCliJobRuntime(options);
  const template = 'reviewed template bytes', helper = 'generated helper bytes';
  const manifest = { schema: 'metaengine.codex-cli.job-runtime.v1', build_mode: 'PRECOMPILED_FRAMEWORK_CSHARP',custody_protocol:CODEX_CLI_JOB_PROTOCOL,
    template_sha256: sha(template), csharp_sha256: '1'.repeat(64), assembly_sha256: '2'.repeat(64),
    helper_sha256: sha(helper), compiler_executable_sha256: '3'.repeat(64) };
  for (const file of [runtime.helperPath, runtime.manifestPath, runtime.templatePath].filter(Boolean)) fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(runtime.helperPath, helper);
  if (runtime.templatePath) fs.writeFileSync(runtime.templatePath, template);
  const writeManifest = value => fs.writeFileSync(runtime.manifestPath, JSON.stringify(value));
  writeManifest(manifest);
  return { options, runtime, manifest, helper, template, writeManifest };
}

test('source runtime resolves prepared output separately from the reviewed build template', t => {
  const f = fixture(t);
  assert.match(resolveCodexCliJobHelper(f.options), /native-dist[\\/]codex-cli[\\/]codex-cli-job-runner\.ps1$/);
  assert.match(resolveCodexCliJobHelperSource(f.options), /scripts[\\/]codex-cli-job-runner\.ps1$/);
  assert.notEqual(f.runtime.helperPath, f.runtime.templatePath);
  assert.deepEqual(verifyCodexCliJobHelper(f.options), { helperPath: f.runtime.helperPath, helperSha256: sha(f.helper),runtimeManifestSha256:sha(fs.readFileSync(f.runtime.manifestPath)) });
});

test('source preparation refuses a changed template, changed helper and absent manifest without fallback', t => {
  const f = fixture(t);
  fs.writeFileSync(f.runtime.templatePath, 'later source bytes');
  assert.throws(() => verifyCodexCliJobHelper(f.options), /runtime_template_changed/);
  fs.writeFileSync(f.runtime.templatePath, f.template);
  fs.writeFileSync(f.runtime.helperPath, 'later generated bytes');
  assert.throws(() => verifyCodexCliJobHelper(f.options), /helper_digest_mismatch/);
  fs.writeFileSync(f.runtime.helperPath, f.helper);
  fs.unlinkSync(f.runtime.manifestPath);
  assert.throws(() => verifyCodexCliJobHelper(f.options), /runtime_unprepared/);
  assert.equal(fs.readFileSync(f.runtime.templatePath, 'utf8'), f.template);
});

test('runtime manifest requires its fixed build mode and every build-chain digest', t => {
  const f = fixture(t);
  for (const change of [{ schema: 'unknown' },{custody_protocol:'LEGACY'}, { build_mode: 'COMPILE_ON_LAUNCH' },
    ...['template_sha256', 'csharp_sha256', 'assembly_sha256', 'helper_sha256', 'compiler_executable_sha256'].map(key => ({ [key]: 'invalid' }))]) {
    f.writeManifest({ ...f.manifest, ...change });
    assert.throws(() => verifyCodexCliJobHelper(f.options), /runtime_manifest_invalid/);
  }
  fs.writeFileSync(f.runtime.manifestPath, '{broken');
  assert.throws(() => verifyCodexCliJobHelper(f.options), /runtime_manifest_invalid/);
});

test('packaged binding comes from the app archive and cannot be replaced by a physical resource manifest', t => {
  const f = fixture(t, true);
  assert.equal(f.runtime.templatePath, null);
  assert.match(f.runtime.manifestPath, /app\.asar[\\/]native-coding-job-runtime\.json$/);
  assert.throws(() => resolveCodexCliJobHelperSource(f.options), /packaged_source_template_unavailable/);
  assert.equal(verifyCodexCliJobHelper(f.options).helperSha256, sha(f.helper));
  fs.writeFileSync(f.runtime.helperPath, 'foreign helper');
  fs.writeFileSync(path.join(path.dirname(f.runtime.helperPath), 'manifest.json'), JSON.stringify({ ...f.manifest, helper_sha256: sha('foreign helper') }));
  assert.throws(() => verifyCodexCliJobHelper(f.options), /helper_digest_mismatch/);
});

test('explicit disposable helpers require their own exact hash and reject directories or oversized files', t => {
  const f = fixture(t);
  assert.throws(() => verifyCodexCliJobHelper({ helperPath: f.runtime.helperPath }), /helper_pin_required/);
  assert.throws(() => verifyCodexCliJobHelper({ ...f.options, expectedHelperSha256: sha(f.helper) }), /helper_pin_requires_explicit_path/);
  const explicit = { helperPath: f.runtime.helperPath, expectedHelperSha256: sha(f.helper) };
  assert.equal(verifyCodexCliJobHelper(explicit).helperSha256, sha(f.helper));
  fs.writeFileSync(f.runtime.helperPath, Buffer.alloc(4 * 1024 * 1024 + 1));
  assert.throws(() => verifyCodexCliJobHelper(explicit), /helper_unreadable/);
  fs.unlinkSync(f.runtime.helperPath); fs.mkdirSync(f.runtime.helperPath);
  assert.throws(() => verifyCodexCliJobHelper(explicit), /helper_unreadable/);
});

test('helper tampering after controller construction is rejected before any child or input effect', async t => {
  const f = fixture(t), platform = Object.getOwnPropertyDescriptor(process, 'platform'), originalSpawn = childProcess.spawn;
  let spawns = 0;
  Object.defineProperty(process, 'platform', { ...platform, value: 'win32' });
  childProcess.spawn = () => { spawns++; throw Error('must_not_spawn'); }; syncBuiltinESMExports();
  t.after(() => { childProcess.spawn = originalSpawn; syncBuiltinESMExports(); Object.defineProperty(process, 'platform', platform); });
  const controller = createCodexCliWindowsProcessController({ helperPath: f.runtime.helperPath, expectedHelperSha256: sha(f.helper),
    powershellPath: path.resolve('fixed-powershell.exe') });
  fs.writeFileSync(f.runtime.helperPath, 'changed after construction');
  await assert.rejects(controller.spawn({ executablePath: path.resolve('unused-worker.exe'), cwd: path.resolve('unused-worktree'),
    args: [], expectedExecutableSha256: 'a'.repeat(64), runId: '11111111-1111-4111-8111-111111111111', timeoutMs: 1000 }), /helper_digest_mismatch/);
  assert.equal(spawns, 0);
});
